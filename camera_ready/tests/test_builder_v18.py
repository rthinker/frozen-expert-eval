"""Appendix condensation preserves results and makes current/historical locations explicit."""
import csv
import importlib.util
import json
import subprocess
import sys

import pytest
from pathlib import Path

CR = Path(__file__).resolve().parents[1]
BUILDER = CR / 'scripts/authoring/generate_camera_ready_tables_v18.py'


def builder():
    spec = importlib.util.spec_from_file_location('tables_v18', BUILDER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.INPUTS = CR / 'inputs'
    return module


def run(out):
    return subprocess.run([sys.executable, '-B', str(BUILDER), '--inputs', str(CR / 'inputs'),
                           '--out', str(out)], capture_output=True, text=True)


def test_current_table_layout_and_labels():
    new = builder()
    ledger = new.Ledger()
    current = {label: fn(ledger) for label, fn in new.ALL_TABLES}
    assert len(new.PAPER_TABLES) == 25
    assert new.CURRENT_PAPER_NAMES["sensitivity"] == "Table A1"
    assert "sensitivity" not in new.UNLABELED
    assert "Non-deployable" not in current["ladder"]
    assert "Core PS baselines" in current["methods"]
    assert new.CURRENT_PAPER_NAMES['cost'] == 'Table A21'
    assert new.CURRENT_PAPER_NAMES['tiers'] == 'Table A22'
    assert new.ADDITIONAL_LABELS == {'mde', 'heuristics', 'sensitivity_heads'}


def test_public_rebuild_preserves_ledger_and_separates_additional_tables(tmp_path):
    # Reusing an older authoring output must not leave retired tables in the paper directory.
    paper = tmp_path / 'tables/paper'
    paper.mkdir(parents=True)
    for label in ['mde', 'heuristics', 'sensitivity_heads']:
        (paper / f'{label}.tex').write_text(
            '% generated by camera_ready/scripts/authoring/generate_camera_ready_tables_v17.py\nold',
            encoding='utf-8')
    result = run(tmp_path)
    assert result.returncode == 0, result.stderr
    def rows(path):
        with path.open(encoding='utf-8', newline='') as stream:
            return list(csv.DictReader(stream))
    expected = rows(CR / 'provenance/05_number_provenance.csv')
    actual = rows(tmp_path / '05_number_provenance.csv')
    assert len(actual) == 1937 and actual == expected
    assert 'posted numbers: 96/96 agree, 0 disagree or missing' in result.stdout
    assert len(list(paper.glob('*.tex'))) == 25
    assert {p.stem for p in (tmp_path / 'tables/additional').glob('*.tex')} == {
        'mde', 'heuristics', 'sensitivity_heads'}
    locations = json.loads((tmp_path / 'paper_table_locations.json').read_text(encoding='utf-8'))
    assert locations['printed_tables'] == 25
    assert locations['tables']['ladder']['text_quantity_ids'] == [
        'A2.clip4.oracle_domain', 'A2.arch6.oracle_domain']
    assert all(locations['tables'][label]['status'] == 'additional'
               for label in ['mde', 'heuristics', 'sensitivity_heads'])
    subset = locations['tables']['small_sets']['quantity_ids']
    assert len([q for q in subset if q.endswith('.logo.delta_n500')]) == 4
    assert not any(q.endswith('.logo.delta_n500') for q in locations['tables']['main']['quantity_ids'])


@pytest.mark.parametrize('label', ['mde', 'sensitivity_heads'])
def test_unrecognized_retired_file_is_not_moved_or_overwritten(tmp_path, label):
    path = tmp_path / 'tables/paper' / f'{label}.tex'
    path.parent.mkdir(parents=True)
    path.write_text('hand-written content', encoding='utf-8')
    result = run(tmp_path)
    assert result.returncode != 0 and 'Refusing to move a non-generated file' in result.stderr
    assert path.read_text(encoding='utf-8') == 'hand-written content'
