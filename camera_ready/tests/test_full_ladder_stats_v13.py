"""Check the current rendering of the supplied LOGO statistics."""
import importlib.util
import json
import re
from pathlib import Path

CR = Path(__file__).resolve().parents[1]
SCRIPT = CR / "scripts" / "authoring" / "full_ladder_stats_v13.py"
MIT = CR / "output" / "results" / "mitigation"


def _stats(path=SCRIPT, name="full_ladder_stats_v13"):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _stored():
    return json.loads((MIT / "mitigation_stats.json").read_text(encoding="utf-8"))


def test_the_stored_numbers_file_is_version_13s_rendering_of_the_stored_statistics():
    md = (MIT / "mitigation_numbers.md").read_text(encoding="utf-8")
    assert md == _stats().numbers_markdown(_stored())
    assert "Generated by `camera_ready/scripts/authoring/full_ladder_stats_v13.py`" in md
    for line in ("| Tables A11 and A14; also the Abstract, Sec. 1 and 5.1, App. A and F | 95% CI | [+0.024, +0.140] |",
                 "| Tables 1 and A14; also the Abstract, Sec. 5.1, App. A and F | folds positive | 7 of 8 |",
                 "| Table 2; also Sec. 5.4, App. A and F | standard-LOGO contrast, arch6 (Table 2's protocol difference) "
                 "| +0.025 |",
                 "| Table 2; also App. A; weak6's also in the Abstract, Sec. 5.4, App. G and the checklist | baseline "
                 "inflation, arch6 / weak6 | +0.074 / +0.172 |"):
        assert line in md, line
    where = [ln.split(" | ")[0] for ln in md.splitlines() if ln.startswith("| ")]
    assert len(where) > 60 and not [w for w in where if "A24" in w or re.search(r"\bK\b", w)]
    assert "distortion" not in md


